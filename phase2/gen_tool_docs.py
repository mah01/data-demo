"""
Regenerate phase2/TOOLS.md from the runtime operations (signatures + docstrings),
so the tool reference cannot drift from the code.

    python3 -m phase2.gen_tool_docs
"""
import inspect
import re
from pathlib import Path

from phase2.runtime import Runtime
from phase2.tests.examples import EXAMPLES

GROUPS = [("meta_", "Metadata"), ("erp_", "ERP / Finance"), ("crm_", "CRM / Sales"), ("payroll_", "Payroll / People"),
          ("identity_", "Identity / Mappings")]


def _type(annotation):
    text = inspect.formatannotation(annotation) if annotation is not inspect.Parameter.empty else "any"
    return re.sub(r"\s*\|\s*None", "?", text)


def main():
    ops = Runtime().operations()
    out = ["# NordFlow runtime tools", "",
           "Generated by `python3 -m phase2.gen_tool_docs` from the query-layer signatures and docstrings. "
           "Every tool is read-only. `?` marks an optional parameter. The example arguments are the ones the "
           "test suite runs against the fixture data.", ""]
    for prefix, title in GROUPS:
        out += [f"## {title}", ""]
        for name, fn in ops.items():
            if not name.startswith(prefix):
                continue
            sig = inspect.signature(fn)
            out += [f"### `{name}`", "", inspect.cleandoc(fn.__doc__), ""]
            out += ["| parameter | type | default |", "|---|---|---|"] if sig.parameters else ["No parameters."]
            for p in sig.parameters.values():
                default = "required" if p.default is inspect.Parameter.empty else f"`{p.default!r}`"
                out.append(f"| `{p.name}` | `{_type(p.annotation)}` | {default} |")
            out += ["", f"Example: `{name}({', '.join(f'{k}={v!r}' for k, v in EXAMPLES[name].items())})`", ""]
    path = Path(__file__).parent / "TOOLS.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {path} ({len(ops)} tools)")


if __name__ == "__main__":
    main()
