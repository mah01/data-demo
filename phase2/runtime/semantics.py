class Semantics:
    """Value classification backed by data/mappings/value_mappings.csv."""

    def __init__(self, mappings_folder):
        rows = mappings_folder.table("value_mappings")
        self._map = {}
        self._market_aliases, self._category_aliases = {}, {}
        for r in rows:
            self._map[(r["domain"], r["system"], r["source_value"])] = r["canonical_value"]
            aliases = self._market_aliases if r["domain"] == "market" else self._category_aliases
            aliases[fold(r["source_value"])] = r["canonical_value"]
            aliases[fold(r["canonical_value"])] = r["canonical_value"]
        for code, name in CONCEPTS["markets"]["codes"].items():
            self._market_aliases[fold(name)] = code
        for r in rows:  # ERP product groups by name as well as number
            if r["domain"] == "product_category" and r["system"] == "erp":
                self._category_aliases[fold(r["canonical_value"])] = r["canonical_value"]

    def classify(self, domain, system, value):
        return self._map.get((domain, system, value)) if value not in (None, "") else None

    def normalize_market(self, value):
        """User input -> market code. Accepts codes and any known country label."""
        if value in (None, ""):
            return None
        code = self._market_aliases.get(fold(str(value)))
        if code is None:
            raise ValueError(f"Unknown market '{value}'. Use one of DK/SE/DE or Denmark/Sweden/Germany.")
        return code

    def normalize_category(self, value):
        if value in (None, ""):
            return None
        cat = self._category_aliases.get(fold(str(value)))
        if cat is None:
            raise ValueError(f"Unknown product category '{value}'. Use Equipment, Components or Service.")
        return cat

    def market_name(self, code):
        return CONCEPTS["markets"]["codes"].get(code)


def semantics_topic(topic=None):
    topics = {"systems": SYSTEMS, **CONCEPTS}
    if topic is None:
        return topics
    if topic not in topics:
        raise ValueError(f"Unknown topic '{topic}'. Available: {', '.join(topics)}")
    return {topic: topics[topic]}
